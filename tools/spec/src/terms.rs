//! The term table (`corpus.registry.term`): each fragment's `[term]` entries, the
//! findings a homonym or a bad entry raises, the glossary and Vale rule rendered from
//! them, and the first-use ratchet over guides.

use crate::corpus::*;
use crate::util::*;
use regex::Regex;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

pub const GLOSSARY: &str = "spec/glossary.md";
pub const VALE_TERMS: &str = ".vale/styles/WriteTechnically/Terms.yml";
const FIRST_USE: &str = "term-first-use";

/// Every registered term with its entry and the contract registering it.
pub fn all(c: &Corpus) -> Vec<(&str, &str, &TermEntry)> {
    c.reg.fragments.iter().flat_map(|(contract, fr)| fr.term.iter().map(move |(t, e)| (t.as_str(), contract.as_str(), e))).collect()
}

fn gloss_cap(c: &Corpus) -> usize {
    c.reg
        .fragments
        .get("corpus")
        .and_then(|fr| fr.limit.get("corpus-term-gloss-words"))
        .and_then(|l| l.value.as_integer())
        .unwrap_or(25) as usize
}

/// `corpus.registry.bad-term`.
pub fn check(c: &Corpus) -> Vec<Finding> {
    let mut out = Vec::new();
    let clauses = c.clause_map();
    let cap = gloss_cap(c);
    let mut homes: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (term, contract, _) in all(c) {
        homes.entry(term).or_default().push(contract);
    }
    for (term, contracts) in &homes {
        if contracts.len() > 1 {
            let frel = format!("spec/terms/{}.toml", contracts[1]);
            out.push(t(&frel, format!("term `{term}` is registered in `{}`", contracts.join("` and `"))));
        }
    }
    for (term, contract, e) in all(c) {
        let frel = format!("spec/terms/{contract}.toml");
        if term != term.to_lowercase() || term.trim() != term || term.is_empty() {
            out.push(t(&frel, format!("term `{term}` is not a lowercase spelling")));
        }
        match clauses.get(&e.clause) {
            None => out.push(t(&frel, format!("term `{term}` names missing clause `{}`", e.clause))),
            Some(cl) if cl.contract != contract => {
                out.push(t(&frel, format!("term `{term}` names clause `{}` of another contract", e.clause)))
            }
            Some(_) => {}
        }
        let words = e.gloss.split_whitespace().count();
        if words == 0 {
            out.push(t(&frel, format!("term `{term}` carries no gloss")));
        } else if words > cap {
            out.push(t(&frel, format!("term `{term}` gloss holds {words} words, over {cap}")));
        }
        for a in &e.avoid {
            if homes.contains_key(a.to_lowercase().as_str()) {
                out.push(t(&frel, format!("term `{term}` avoids `{a}`, itself a registered term")));
            }
        }
    }
    out
}

fn t(file: &str, msg: String) -> Finding {
    Finding::new("registry", file, 0, "SpecTerm", msg)
}

/// `spec/glossary.md` (`corpus.registry.glossary`).
pub fn glossary(c: &Corpus) -> String {
    let mut rows = all(c);
    rows.sort_by_key(|(term, _, _)| *term);
    let mut s = String::new();
    s.push_str("# Glossary\n\n");
    s.push_str("Generated by `contextful-spec state` from the `[term]` tables of `spec/terms/`; not authored.\n\n");
    s.push_str("| Term | Meaning | Defined by |\n| --- | --- | --- |\n");
    for (term, _, e) in rows {
        let _ = writeln!(s, "| {term} | {} | {{{{{}}}}} |", e.gloss.replace('|', "\\|"), e.clause);
    }
    s
}

/// `.vale/styles/WriteTechnically/Terms.yml` (`corpus.registry.vale-terms`).
pub fn vale_terms(c: &Corpus) -> String {
    let mut swaps: BTreeMap<String, &str> = BTreeMap::new();
    for (term, _, e) in all(c) {
        for a in &e.avoid {
            swaps.insert(a.to_lowercase(), term);
        }
    }
    let mut s = String::new();
    s.push_str("# Generated by `contextful-spec state` from the `[term]` tables of `spec/terms/`; not authored.\n");
    s.push_str("extends: substitution\n");
    s.push_str("message: \"Use '%s' instead of '%s' — one word, one meaning (spec/glossary.md).\"\n");
    s.push_str("level: error\nignorecase: true\nswap:\n");
    for (avoid, term) in swaps {
        let _ = writeln!(s, "  {avoid}: {term}");
    }
    s
}

/// A term's spellings as a case-insensitive pattern: its words in order, the last
/// inflected by `s`, `es`, `d`, `ed` or `ing`, a final `e` dropped before `ing`.
fn pattern(term: &str) -> Regex {
    let words: Vec<&str> = term.split_whitespace().collect();
    let (last, head) = words.split_last().expect("a term holds a word");
    let last = match last.strip_suffix('e') {
        Some(stem) => format!("(?:{}(?:s|d)?|{}ing)", regex::escape(last), regex::escape(stem)),
        None => format!("{}(?:s|es|ed|ing)?", regex::escape(last)),
    };
    let mut parts: Vec<String> = head.iter().map(|w| regex::escape(w)).collect();
    parts.push(last);
    Regex::new(&format!(r"(?i)\b{}\b", parts.join(r"\s+"))).unwrap()
}

/// One guide paragraph: its first line and its text, lines joined by a space.
fn paragraphs(d: &Doc) -> Vec<(usize, String)> {
    let mut out: Vec<(usize, String)> = Vec::new();
    let mut open = false;
    for (n, l, k) in d.each() {
        match k {
            LineKind::Blank | LineKind::Heading | LineKind::Fence | LineKind::Code | LineKind::Front => open = false,
            _ if open => {
                let last = out.last_mut().unwrap();
                last.1.push(' ');
                last.1.push_str(l);
            }
            _ => {
                out.push((n, l.to_string()));
                open = true;
            }
        }
    }
    out
}

/// Each guide's first use of a term in a paragraph lacking the term's defining pointer,
/// as (file, line, term).
pub fn first_use_misses(c: &Corpus) -> Vec<(String, usize, String)> {
    let terms: Vec<(&str, &TermEntry, Regex)> = all(c).into_iter().map(|(term, _, e)| (term, e, pattern(term))).collect();
    let mut out = Vec::new();
    for d in c.guides() {
        let mut seen: BTreeSet<&str> = BTreeSet::new();
        for (n, text) in paragraphs(d) {
            let points: BTreeSet<String> = pointers(&text).into_iter().collect();
            let plain = strip_pointers(&without_ticks(&text), " ");
            for (term, e, re) in &terms {
                if seen.contains(term) || !re.is_match(&plain) {
                    continue;
                }
                seen.insert(term);
                if !points.contains(&e.clause) {
                    out.push((d.rel.clone(), n, term.to_string()));
                }
            }
        }
    }
    out
}

/// The `term-first-use` ratchet (`corpus.registry.term-first-use`).
pub fn first_use_live(c: &Corpus) -> crate::ratchet::Live {
    crate::ratchet::Live { key: FIRST_USE.into(), count: first_use_misses(c).len(), check: "registry", code: "SpecTermFirstUse" }
}

/// The ratchet's finding, naming each first use without its pointer when the count rises.
pub fn first_use(c: &Corpus) -> Vec<Finding> {
    let live = first_use_live(c);
    let Some(mut finding) = crate::ratchet::compare(c, &live) else { return Vec::new() };
    if crate::ratchet::ceiling(c, FIRST_USE).is_some_and(|cap| live.count > cap) {
        let misses: Vec<String> = first_use_misses(c).into_iter().map(|(file, line, term)| format!("{file}:{line} `{term}`")).collect();
        let _ = write!(finding.message, "; first uses without the defining pointer: {}", misses.join(", "));
    }
    vec![finding]
}
